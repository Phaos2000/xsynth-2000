#include "DssiImport.h"
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <stdexcept>
namespace fs = std::filesystem;
struct Preset {
  std::string name, notes;
  xs::State state;
  int bank;
};
std::string read(const fs::path &p) {
  std::ifstream in(p, std::ios::binary);
  if (!in)
    throw std::runtime_error("Cannot read " + p.string());
  return {std::istreambuf_iterator<char>(in), {}};
}
int main(int argc, char **argv) {
  try {
    if (argc != 3)
      throw std::runtime_error("Expected factory source root and output header");
    fs::path source = argv[1];
    std::vector<Preset> presets;
    std::vector<fs::path> files;
    for (auto &f : fs::directory_iterator(source / "xsynth-1.0.2"))
      if (f.path().extension() == ".Xpatch")
        files.push_back(f.path());
    std::sort(files.begin(), files.end());
    for (auto &file : files) {
      auto b = read(file);
      std::vector<uint8_t> bytes(b.begin(), b.end());
      xs::State state{};
      if (!xs::importPatch(bytes, state))
        throw std::runtime_error("Original patch failed");
      presets.push_back({file.stem().string(),
                         "Original physical Xpatch values; CLASSIC historical renderer; extension "
                         "defaults neutral.",
                         state, 0});
    }
    for (int bank = 1; bank <= 2; ++bank) {
      auto raw = read(source / "xsynth-dssi-0.9.4" /
                      (bank == 1 ? "factory_patches.Xsynth" : "version_0.1_patches.Xsynth"));
      auto parsed = xs::dssi::parse(raw);
      if (!parsed.error.empty() || parsed.converted != parsed.entries.size())
        throw std::runtime_error("Official bank failed conversion");
      for (auto &e : parsed.entries) {
        std::string notes;
        for (auto &w : e.warnings) {
          if (!notes.empty())
            notes += " ";
          notes += w;
        }
        presets.push_back({e.patch.name, notes, e.state, bank});
      }
    }
    std::ofstream out(argv[2], std::ios::binary);
    if (!out)
      throw std::runtime_error("Output failed");
    out << "// Generated by tools/GenerateFactory.cpp. Historical notices: "
           "factory/BANKS.md.\n#pragma once\n#include \"Core.h\"\nnamespace xs::factory {\nstruct "
           "Preset {const char* name;const char* notes;State state;int bank;};\nstruct Bank {const "
           "char* name;int first,count;};\ninline constexpr Bank Banks[]={{\"XSYNTH "
           "1.0.2\",0,11},{\"XSYNTH-DSSI FACTORY\",11,14},{\"XSYNTH-DSSI 0.1\",25,25}};\ninline "
           "constexpr Preset Presets[]={\n";
    for (auto &p : presets) {
      out << "{" << std::quoted(p.name) << "," << std::quoted(p.notes) << ",{{";
      for (size_t i = 0; i < p.state.size(); ++i) {
        if (i)
          out << ',';
        out << std::hexfloat << p.state[i];
      }
      out << "}}," << p.bank << "},\n";
    }
    out << "};\ninline constexpr int Count=sizeof(Presets)/sizeof(Presets[0]);\n} // namespace "
           "xs::factory\n";
    if (!out)
      throw std::runtime_error("Header write failed");
    std::cout << "Generated " << presets.size() << " immutable native factory states\n";
    return 0;
  } catch (const std::exception &e) {
    std::cerr << e.what() << '\n';
    return 1;
  }
}
